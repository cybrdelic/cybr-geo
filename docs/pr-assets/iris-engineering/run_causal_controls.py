"""Reproduce bound IRIS causal controls with the shared engineering runtime.

From the repository root after installing the project::

    python docs/pr-assets/iris-engineering/run_causal_controls.py \
        --run outputs/iris09 --out outputs/iris09-controls

The nominal run must be generated by the current source. The optional --native
argument locates its existing native directory without changing its identity.
Removing a numerical closure leaves the CAD unchanged; it does not represent
a physically modified assembly or qualify hardware.
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
from pathlib import Path

from mechanism_lab.causal_runtime import CausalSimulation
from mechanism_lab.engineering_source import load_project, verify_native_build, verify_native_source_binding
from mechanism_lab.physical_model import PhysicalModel, digest


def read_json(path):
    return json.loads(path.read_text(encoding='utf-8'))


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_json(path, value):
    path.write_text(json.dumps(value, indent=2, allow_nan=False)+'\n', encoding='utf-8')


def run_controls(run, output, native=None):
    run, output = Path(run), Path(output)
    report = read_json(run/'engineering.json')
    if report.get('name') != 'iris09' or not report.get('passed'):
        raise ValueError('A successful current-source IRIS nominal run is required')
    native = Path(native) if native is not None else Path(report['native']['directory'])
    project, source_files = load_project('iris09')
    receipt = verify_native_build(native, project.specification, source_files=source_files)
    binding = verify_native_source_binding(native, project.specification, source_files, receipt=receipt)
    physical, control, parameters = project.compile_physics(project.specification, native_directory=native)
    physical.provenance.update(native_build_sha256=digest(receipt), native_source_binding_sha256=digest(binding),
                               design_source_files=source_files)
    # Native PinnedLink metadata uses immutable tuples. Compare its exact JSON
    # representation with the reloaded trace, without rounding numeric values.
    physical_source = json.loads(json.dumps(physical.to_source(), allow_nan=False))
    nominal_path = run/'simulation'/'trace.json.gz'
    nominal = json.loads(gzip.decompress(nominal_path.read_bytes()))
    reference_source = dict(source_files=source_files, task_parameters=parameters)
    expected = dict(model_sha256=digest(physical_source), control_sha256=digest(control),
                    reference_sha256=digest(reference_source))
    for key, identity in expected.items():
        if nominal.get(key) != identity:
            raise ValueError(f'Nominal trace has stale or incompatible {key}')
    if (report['native_build_sha256'] != digest(receipt)
            or report['native_source_binding_sha256'] != digest(binding)
            or nominal['physical_source'] != physical_source
            or nominal['reference_source'] != reference_source):
        raise ValueError('Nominal trace and native/source receipts do not match')
    if output.exists() and any(output.iterdir()):
        raise ValueError('Choose an empty output directory to preserve existing evidence')
    output.mkdir(parents=True, exist_ok=True)
    runner = dict(filename=Path(__file__).name, sha256=sha256(Path(__file__)),
                  arguments=dict(run=str(run), native=str(native), out=str(output)),
                  scope='Exact reproduction script bytes; separate from unchanged task reference identity')
    summary = dict(schema='cybrgeo-iris-causal-controls/1', runner=runner,
        native_build_sha256=digest(receipt), native_source_binding_sha256=digest(binding),
        nominal_model_sha256=expected['model_sha256'], control_sha256=expected['control_sha256'],
        reference_sha256=expected['reference_sha256'], nominal_trace_path=str(nominal_path),
        nominal_trace_sha256=sha256(nominal_path), runtime_implementation=nominal['runtime_implementation'], cases={})
    for case in ('power_off', 'disabled_first_closure'):
        model = PhysicalModel.from_source(physical_source)
        options = {'power': False} if case == 'power_off' else {}
        if case == 'disabled_first_closure':
            equality = model.root.find('equality')
            equality.remove(equality.find("connect[@name='rod_00_closure']"))
            model.provenance['numerical_counterfactual'] = dict(disabled_constraint='rod_00_closure',
                native_geometry='unchanged; this is not an alternate physical hardware assembly',
                purpose='Falsify hidden prescribed follower motion by removing its force-transmitting closure')
        directory = output/case
        model.write(directory)
        write_json(directory/'control-source.json', control)
        runtime = CausalSimulation(model, control, lambda t: project.reference(t, parameters),
                                   options=options, reference_source=reference_source)
        result = runtime.run(project.duration_s, output=directory/'simulation')
        if result['runtime_implementation'] != nominal['runtime_implementation']:
            raise ValueError('Runtime implementation differs from the nominal evidence; regenerate nominal first')
        checks = project.requirements(result, parameters)
        result.update(task_parameters=parameters, physical_source=model.to_source(),
                      requirements=checks, causal_control=dict(name=case, runner=runner))
        joints = result['metrics']['joints']
        leaves = {name: value for name, value in joints.items() if name.startswith('leaf_')}
        maxima = {name: value['maximum_position']['value'] for name, value in leaves.items()}
        excursion = {name: max(abs(value['minimum_position']['value']), abs(value['maximum_position']['value']))
                     for name, value in leaves.items()}
        expected_outcome = not checks['passed'] and len(leaves) == 9
        if case == 'power_off':
            expected_outcome = expected_outcome and max(excursion.values()) < 1e-10
        else:
            expected_outcome = (expected_outcome and excursion['leaf_00_hinge'] < 1e-10
                and all(value > .89 for name, value in maxima.items() if name != 'leaf_00_hinge'))
        trace_path = directory/'simulation'/'trace.json.gz'
        with gzip.open(trace_path, 'wt', encoding='utf-8') as stream:
            json.dump(result, stream, separators=(',', ':'), allow_nan=False)
        write_json(directory/'requirements.json', checks)
        summary['cases'][case] = dict(model_sha256=result['model_sha256'], passed=checks['passed'],
            expected_control_outcome_passed=bool(expected_outcome), options=result['options'],
            duration_s=result['duration_s'], steps=result['steps'], leaf_maximum_positions_rad=maxima,
            trace_path=str(trace_path), trace_sha256=sha256(trace_path), requirements=checks)
        print(f'{case}: expected causal outcome={bool(expected_outcome)}, task passed={checks["passed"]}', flush=True)
        if not expected_outcome:
            write_json(output/'counterfactuals.json', summary)
            raise ValueError(f'{case} did not produce the expected causal contrast')
    write_json(output/'counterfactuals.json', summary)
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--run', type=Path, required=True, help='Current-source successful nominal engineering output')
    parser.add_argument('--native', type=Path, help='Same native artifact directory if relocated; identity is verified')
    parser.add_argument('--out', type=Path, required=True, help='New or empty output directory')
    args = parser.parse_args()
    run_controls(args.run, args.out, args.native)


if __name__ == '__main__':
    main()

"""Blender lowering of ComponentAssembly; no mechanism-specific rig definition.

Only source-declared meshes, materials and poses are used. Existing objects can
retain their exact mesh bytes, but their animation is generated by the assembly.
This adapter does not select appearance from mechanical density or strength.
"""
from pathlib import Path
import hashlib
import math
import numpy as np


def mesh_digest(mesh):
    vertices=np.empty(len(mesh.vertices)*3,np.float32)
    mesh.vertices.foreach_get('co',vertices);mesh.calc_loop_triangles()
    faces=np.array([t.vertices[:] for t in mesh.loop_triangles],np.int32)
    return hashlib.sha256(vertices.tobytes()+faces.tobytes()).hexdigest()


def realize(assembly, root, *, scene=None, id_property='component_id', replace_ids=(), smooth_angle=35.,purpose='manufacturing',lower_static_volumes=False):
    assembly.require_export(purpose)
    import bpy
    from mathutils import Matrix
    scene=scene or bpy.context.scene;root=Path(root);changed=set(replace_ids)
    objects={int(o[id_property]):o for o in scene.objects if o.type=='MESH' and id_property in o}
    if set(objects)-set(assembly.parts):
        raise ValueError('Scene contains components absent from the authoritative assembly')
    before={pid:mesh_digest(o.data) for pid,o in objects.items() if pid not in changed}
    bodies={body:bpy.data.objects.new(f'assembly_body_{body}',None) for body in assembly.body_parents}
    for body,obj in bodies.items():
        scene.collection.objects.link(obj);obj['assembly_body']=str(body);obj.rotation_mode='QUATERNION'
        parent=assembly.body_parents[body]
        if parent is not None:obj.parent=bodies[parent]
        for frame in assembly.frames:
            pose=assembly.body_pose(frame,body)
            if parent is not None:pose=np.linalg.inv(assembly.body_pose(frame,parent))@pose
            obj.matrix_basis=Matrix(pose.tolist())
            for path in ('location','rotation_quaternion','scale'):obj.keyframe_insert(data_path=path,frame=int(frame))
    rotating={pid for motion in assembly.motions for pid in motion.rotating_ids}
    for pid,part in assembly.parts.items():
        if pid in changed or pid not in objects:
            if part.get('mesh_units')!='m':raise ValueError('Mesh requires explicit metre units')
            with np.load(root/part['mesh_path'],allow_pickle=False) as arrays:
                v,f=arrays['vertices'],arrays['faces']
                if v.ndim!=2 or v.shape[1]!=3 or f.ndim!=2 or f.shape[1]!=3 or not len(f) or not np.isfinite(v).all() or f.dtype.kind not in 'iu' or f.min()<0 or f.max()>=len(v):raise ValueError('Invalid indexed component mesh')
                mesh=bpy.data.meshes.new(part['name']+'_CAD')
                mesh.from_pydata(arrays['vertices'].tolist(),[],arrays['faces'].tolist());mesh.update()
                # Explicit source-authored optical coordinates are independent of geometry/process.
                if part.get('optical_coordinates') is not None:
                    from .optical_coordinates import apply_to_mesh
                    apply_to_mesh(mesh,part['optical_coordinates'],purpose=purpose)
            if pid in objects:objects[pid].data=mesh
            else:
                objects[pid]=bpy.data.objects.new(part['name'],mesh);scene.collection.objects.link(objects[pid])
            for polygon in mesh.polygons:polygon.use_smooth=True
            if hasattr(mesh,'set_sharp_from_angle'):mesh.set_sharp_from_angle(angle=math.radians(smooth_angle))
        obj=objects[pid];obj.name=f'{pid:03}_{part["name"]}';obj[id_property]=pid
        material=bpy.data.materials.get(part['optical_material'])
        if material is None:raise ValueError('Missing declared optical material '+part['optical_material'])
        obj.data.materials.clear();obj.data.materials.append(material)
        obj.hide_render=False;obj.animation_data_clear();obj.constraints.clear();obj.parent=bodies[part['body_index']]
        obj.matrix_parent_inverse=Matrix.Identity(4);obj.matrix_basis=Matrix.Identity(4)
        obj.rotation_mode='QUATERNION'
        for name in ('physical_material','mass_kg','role','group'):
            if name in part:obj[name]=part[name]
        if 'step_sha256' in part:obj['source_step_sha256']=part['step_sha256']
        if pid in rotating:
            for frame in assembly.frames:
                obj.matrix_basis=Matrix(assembly.local_pose(frame,pid,part['body_index']).tolist())
                for path in ('location','rotation_quaternion','scale'):obj.keyframe_insert(data_path=path,frame=int(frame))
    for obj in [*bodies.values(),*(objects[pid] for pid in rotating)]:
        action=obj.animation_data.action
        for layer in action.layers:
            for strip in layer.strips:
                for slot in action.slots:
                    bag=strip.channelbag(slot)
                    if bag:
                        for curve in bag.fcurves:
                            for key in curve.keyframe_points:key.interpolation='LINEAR'
    volume_receipts=[]
    if lower_static_volumes:
        from .blender_volume import lower_material
        for name in sorted({p['optical_material'] for p in assembly.parts.values()}):
            receipt=lower_material(bpy.data.materials[name])
            if receipt is not None:volume_receipts.append(receipt)
    unchanged=[pid for pid,checksum in before.items() if mesh_digest(objects[pid].data)==checksum]
    if len(unchanged)!=len(before):raise RuntimeError('Unchanged source geometry was altered')
    return dict(volume_lowering=volume_receipts,part_count=len(objects),body_rig_nodes=len(bodies),component_motion_nodes=len(rotating),animation_authorities=len(bodies)+len(rotating),unchanged_geometry_count=len(unchanged),unchanged_ids=sorted(unchanged),
        no_robot_parts_hidden=all(not o.hide_render for o in objects.values()),
        reference_motion_only=True,rigid_body_dynamics_rerun=False,hardware_rating_established=False)
